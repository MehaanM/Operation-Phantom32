void setup() {
  Serial.begin(SERIAL_BAUD);
  delay(100);
  print_banner();
  if (!psram_alloc_all()) {
    Serial.println("[doom] PSRAM alloc failed — halting");
    for (;;)
      delay(1000);
  }
  g_boot_ts = millis();

  // ---- LittleFS ----
  if (!LittleFS.begin(true)) {
    Serial.println("[doom] LittleFS mount failed — formatting");
    LittleFS.format();
    LittleFS.begin(false);
  }
  Serial.printf("[doom] FS: %u/%u bytes used\n", LittleFS.usedBytes(), LittleFS.totalBytes());

  // ---- Safety ----
  fsLockInit();
  safety_load();
  safety_autostop_hook = []() {
    if (g_active)
      tool_stop(g_active);
  };

  // ---- Auth init (must run before WiFi AP — provides per-device AP password) ----
  auth_init();

  // ---- WiFi AP ----
  WiFi.mode(WIFI_AP_STA);
  wifi_config_t ap_conf = {};
  strlcpy((char *)ap_conf.ap.ssid, AP_SSID, sizeof(ap_conf.ap.ssid));
  strlcpy((char *)ap_conf.ap.password, auth_get_ap_wifi_password(), sizeof(ap_conf.ap.password));
  ap_conf.ap.channel = AP_CHANNEL;
  ap_conf.ap.max_connection = AP_MAX_CLIENTS;
  ap_conf.ap.authmode = WIFI_AUTH_WPA2_PSK;
  ap_conf.ap.ssid_hidden = 0;
  esp_wifi_set_config(WIFI_IF_AP, &ap_conf);
  WiFi.softAP(AP_SSID, auth_get_ap_wifi_password(), AP_CHANNEL, 0, AP_MAX_CLIENTS);
  delay(150);
  Serial.printf("[doom] AP: ssid=%s ip=%s ch=%u\n", AP_SSID, WiFi.softAPIP().toString().c_str(),
                AP_CHANNEL);
  g_current_ch = AP_CHANNEL;

  // ---- Promiscuous mode ----
  tool_wifi_suspend = doom_suspend;
  tool_wifi_resume = doom_resume;
  doom_resume();

  // ---- Remaining security modules (auth_init already called above) ----
  rla_init();

  // ---- Register core routes ----
  safety_routes();
  diag_routes();
  board_routes();
  captivePortalRoutes();
  pcapmgr_routes();
  dashboard_routes();
  system_routes();
  iv_routes();

  // ---- Main endpoints ----
  server.on("/", HTTP_GET, []() {
    if (!auth_check_or_redirect(true))
      return;
    serveHub();
  });
  server.on("/api/modules", HTTP_GET, []() {
    if (!auth_check()) {
      auth_reject();
      return;
    }
    listModules();
  });
  server.on("/api/scan", HTTP_GET, []() {
    if (!auth_check()) {
      auth_reject();
      return;
    }
    scanAPs();
  });

  // ---- Register tools and their routes ----
  register_tools();
  for (int i = 0; i < g_tool_count; i++) {
    if (g_tools[i].routes)
      g_tools[i].routes();
  }

  // ---- Core module routes ----
  server.on("/aegis", HTTP_GET, []() {
    if (!auth_check_or_redirect(true))
      return;
    handleRoot();
  });
  server.on("/cli", HTTP_GET, []() {
    if (!auth_check_or_redirect(true))
      return;
    serveHub();
  });

  // ---- CLI ----
  cli_routes();
  cli_routes_extended();
  ouf_routes();

  // ---- Extended analytical module routes ----
  ext_register_routes();

  // ---- Phase 18-20 API routes ----
  server.on("/api/phantom-doctor", HTTP_GET, []() {
    if (!auth_check()) {
      auth_reject();
      return;
    }
    DiagStatus ds = g_phantom_doctor.overallStatus();
    const char *statusStr = "INCOMPLETE";
    if (ds == DiagStatus::PASS)
      statusStr = "PASS";
    else if (ds == DiagStatus::WARN)
      statusStr = "WARN";
    else if (ds == DiagStatus::FAIL)
      statusStr = "FAIL";
    char buf[256];
    snprintf(buf, sizeof(buf),
             "{\"status\":\"%s\",\"pass\":%u,\"warn\":%u,\"fail\":%u,\"pending\":%u}", statusStr,
             (unsigned)g_phantom_doctor.passCount(), (unsigned)g_phantom_doctor.warnCount(),
             (unsigned)g_phantom_doctor.failCount(), (unsigned)g_phantom_doctor.pendingCount());
    server.send(200, "application/json", buf);
  });

  server.on("/api/resource-profile", HTTP_GET, []() {
    if (!auth_check()) {
      auth_reject();
      return;
    }
    char buf[256];
    snprintf(buf, sizeof(buf), "{\"freeHeap\":%u,\"totalHeap\":%u}",
             (unsigned)g_resource_profiler.systemFreeRam(),
             (unsigned)g_resource_profiler.systemTotalRam());
    server.send(200, "application/json", buf);
  });

  // ---- 404 handler ----
  server.onNotFound([]() {
    // Try to redirect unknown requests to dashboard for captive portal UX
    server.sendHeader("Location", "http://192.168.4.1/dashboard");
    server.send(302, "text/plain", "");
  });

  // ---- Phase 18-20 diagnostics ----
  g_phantom_doctor.registerCheck("Heap", "Free heap above critical threshold");
  g_phantom_doctor.registerCheck("Storage", "LittleFS mounted and readable");
  g_phantom_doctor.registerCheck("WiFi", "AP interface up");

  uint32_t freeHeap = esp_get_free_heap_size();
  g_phantom_doctor.setCheckResult(
      "Heap", freeHeap > HEAP_CRIT_THRESHOLD ? CheckStatus::PASS : CheckStatus::FAIL,
      freeHeap > HEAP_CRIT_THRESHOLD ? "OK" : "Critical");
  g_phantom_doctor.setCheckResult(
      "Storage", LittleFS.totalBytes() > 0 ? CheckStatus::PASS : CheckStatus::FAIL, "");
  g_phantom_doctor.setCheckResult(
      "WiFi", WiFi.softAPIP() != IPAddress() ? CheckStatus::PASS : CheckStatus::FAIL, "");
  g_phantom_doctor.finalise(millis());

  g_resource_profiler.sampleSystem(millis());

  g_quality_scorecard.trackMetric("FreeHeap", "bytes", HEAP_WARN_THRESHOLD, HEAP_CRIT_THRESHOLD,
                                  true);
  g_quality_scorecard.recordValue("FreeHeap", (double)freeHeap);

  // ---- Start server ----
  server.begin();
  Serial.printf("[doom] HTTP server started on port 80\n");

  // ---- Setup all tool modules ----
  for (int i = 0; i < g_tool_count; i++) {
    if (g_tools[i].setup)
      g_tools[i].setup();
  }

  // ---- Channel hop task ----
  xTaskCreate(channel_hop_task, "chan_hop", 2048, nullptr, 1, &g_hop_task);

  Serial.println("[doom] ========================================");
  Serial.println("[doom] Ready!");
  Serial.printf("[doom] Connect: SSID=%s PASS=%s\n", AP_SSID, auth_get_ap_wifi_password());
  Serial.printf("[doom] Browse:  http://%s/dashboard\n", AP_IP);
  Serial.println("[doom] ========================================");
}

// ============================================================
// LOOP
// ============================================================

void loop() {
  server.handleClient();
  safety_tick();

  // Run active tool loops
  for (int i = 0; i < g_tool_count; i++) {
    if (g_tools[i].loop)
      g_tools[i].loop();
  }

  // Heap watchdog
  check_heap();

  // Age scan cache every 5s (full build only — scan_result_cache.h not in lite)
  static uint32_t last_age = 0;
  uint32_t now = millis();
#ifndef PHANTOM32_LITE
  if (now - last_age > 5000) {
    last_age = now;
    src_age_entries();
  }
#else
  (void)last_age;
  (void)now;
#endif

  // Phase 18-20: periodic resource sampling every 30 s
  static uint32_t g_last_profiler_sample = 0;
  if (now - g_last_profiler_sample >= 30000) {
    g_last_profiler_sample = now;
    g_resource_profiler.sampleSystem(now);
    uint32_t heapNow = esp_get_free_heap_size();
    g_quality_scorecard.recordValue("FreeHeap", (double)heapNow);
    if (heapNow < HEAP_CRIT_THRESHOLD) {
      g_recovery_engine.recordFailure("LowHeap", "Heap below critical", FailureSeverity::SEV_HIGH,
                                      true, now);
    }
  }

  // Watchdog tap
  g_watchdog_ts = now;

  delay(1);
}
