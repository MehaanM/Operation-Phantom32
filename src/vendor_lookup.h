// ============================================================
// LOOKUP FUNCTION
// Returns vendor name for a given 6-byte MAC address.
// Uses sequential search (table is not sorted by OUI here).
// ============================================================

const char* vnd_lookup(const uint8_t *mac) {
  if (!mac) return "Unknown";
  for (int i = 0; i < VND_TABLE_SIZE; i++) {
    if (VND_TABLE[i].oui[0] == mac[0] &&
        VND_TABLE[i].oui[1] == mac[1] &&
        VND_TABLE[i].oui[2] == mac[2]) {
      return VND_TABLE[i].name;
    }
  }
  // Check locally-administered / multicast / broadcast
  if (mac[0] == 0xFF && mac[1] == 0xFF && mac[2] == 0xFF) return "Broadcast";
  if (mac[0] & 0x01) return "Multicast";
  if (mac[0] & 0x02) return "Locally Administered";
  return "Unknown";
}

const char* vnd_lookup_oui(uint8_t b0, uint8_t b1, uint8_t b2) {
  uint8_t mac[6] = {b0, b1, b2, 0, 0, 0};
  return vnd_lookup(mac);
}

static void vnd_mac_to_str(const uint8_t *m, char *out) {
  snprintf(out, 18, "%02X:%02X:%02X:%02X:%02X:%02X",
           m[0],m[1],m[2],m[3],m[4],m[5]);
}

// ============================================================
// HTTP ROUTES
// ============================================================

static void vnd_handle_lookup() {
  if (!server.hasArg("mac")) {
    server.send(400, "application/json", "{\"error\":\"missing mac\"}");
    return;
  }
  String mac_str = server.arg("mac");
  uint8_t b[6] = {};
  if (sscanf(mac_str.c_str(), "%hhx:%hhx:%hhx:%hhx:%hhx:%hhx",
             &b[0],&b[1],&b[2],&b[3],&b[4],&b[5]) != 6 &&
      sscanf(mac_str.c_str(), "%02hhx%02hhx%02hhx%02hhx%02hhx%02hhx",
             &b[0],&b[1],&b[2],&b[3],&b[4],&b[5]) != 6) {
    server.send(400, "application/json", "{\"error\":\"invalid mac\"}");
    return;
  }
  const char *vendor = vnd_lookup(b);
  char mac_out[18]; vnd_mac_to_str(b, mac_out);
  String s = "{\"mac\":\"" + String(mac_out) + "\"";
  s += ",\"oui\":\"" + String(mac_out).substring(0, 8) + "\"";
  s += ",\"vendor\":\"" + String(vendor) + "\"}";
  server.send(200, "application/json", s);
}

static void vnd_handle_batch() {
  if (!server.hasArg("plain")) {
    server.send(400, "application/json", "{\"error\":\"no body\"}");
    return;
  }
  // Expect newline-separated MAC addresses in body
  String body = server.arg("plain");
  String out = "[";
  bool first = true;
  int pos = 0;
  while (pos < (int)body.length()) {
    int nl = body.indexOf('\n', pos);
    if (nl < 0) nl = body.length();
    String line = body.substring(pos, nl);
    line.trim();
    if (line.length() >= 12) {
      uint8_t b[6] = {};
      if (sscanf(line.c_str(), "%hhx:%hhx:%hhx:%hhx:%hhx:%hhx",
                 &b[0],&b[1],&b[2],&b[3],&b[4],&b[5]) == 6 ||
          sscanf(line.c_str(), "%02hhx%02hhx%02hhx%02hhx%02hhx%02hhx",
                 &b[0],&b[1],&b[2],&b[3],&b[4],&b[5]) == 6) {
        const char *vendor = vnd_lookup(b);
        char mac_out[18]; vnd_mac_to_str(b, mac_out);
        if (!first) out += ","; first = false;
        out += "{\"mac\":\"" + String(mac_out) + "\",\"vendor\":\"" + String(vendor) + "\"}";
      }
    }
    pos = nl + 1;
  }
  out += "]";
  server.send(200, "application/json", out);
}

static void vnd_handle_oui_info() {
  String s = "{\"oui_count\":" + String(VND_TABLE_SIZE) + "}";
  server.send(200, "application/json", s);
}

inline void vnd_routes() {
  server.on("/api/vendor",        HTTP_GET,  vnd_handle_lookup);
  server.on("/api/vendor/batch",  HTTP_POST, vnd_handle_batch);
  server.on("/api/vendor/info",   HTTP_GET,  vnd_handle_oui_info);
}
