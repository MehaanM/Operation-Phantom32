static const int OUI_TABLE_SIZE = sizeof(OUI_TABLE) / sizeof(OUI_TABLE[0]);

// Look up vendor by MAC address
const char* oui_lookup(const uint8_t *mac) {
  for (int i = 0; i < OUI_TABLE_SIZE; i++) {
    if (mac[0] == OUI_TABLE[i].oui[0] &&
        mac[1] == OUI_TABLE[i].oui[1] &&
        mac[2] == OUI_TABLE[i].oui[2]) {
      return OUI_TABLE[i].vendor;
    }
  }
  return "Unknown";
}

// Return true if locally-administered (random MAC)
bool oui_is_random(const uint8_t *mac) {
  return (mac[0] & 0x02) != 0;
}

// Return true if multicast/broadcast
bool oui_is_multicast(const uint8_t *mac) {
  return (mac[0] & 0x01) != 0;
}
